echo "Android project added."

echo "== 3/5 Signing key in your name"
mkdir -p "$KDIR"; chmod 700 "$KDIR"
read -rsp "Key password (8+ characters, write it down): " P1; echo
if [ -f "$KS" ]; then
  keytool -list -keystore "$KS" -storepass "$P1" >/dev/null 2>&1 || { echo "Wrong password for the existing key."; exit 1; }
  echo "Keeping your existing key."
else
  read -rsp "Repeat password: " P2; echo
  [ "$P1" = "$P2" ] && [ ${#P1} -ge 8 ] || { echo "Passwords differ or are shorter than 8 characters."; exit 1; }
  keytool -genkeypair -alias mintoosuite -keyalg RSA -keysize 4096 -validity 10000 -storetype PKCS12 \
    -keystore "$KS" -storepass "$P1" -keypass "$P1" \
    -dname "CN=Muhammad Awais, OU=MintooSuite, O=MintooSuite, L=Islamabad, ST=Islamabad, C=PK"
  chmod 600 "$KS"
fi
echo "Certificate fingerprint (keep this):"
keytool -list -v -keystore "$KS" -storepass "$P1" | grep -E "Owner|SHA256|Valid"
if [ -d "$HOME/storage/shared" ]; then
  mkdir -p "$HOME/storage/shared/MintooSuite_KEY_BACKUP"; cp "$KS" "$HOME/storage/shared/MintooSuite_KEY_BACKUP/"
  echo "Backup copied to phone storage: MintooSuite_KEY_BACKUP. Also copy it OFF this phone (email it to yourself or use a USB drive)."
else
  echo "To make a phone-storage backup, run  termux-setup-storage  and run this script again. Also copy $KS off this phone."
fi

echo "== 4/5 Saving the key as secrets in your GitHub repo"
cd "$REPO"
base64 -w0 "$KS" > "$KDIR/keystore.b64"
if command -v gh >/dev/null && gh auth status >/dev/null 2>&1; then
  gh secret set KEYSTORE_B64 < "$KDIR/keystore.b64"
  printf %s "$P1" | gh secret set KEYSTORE_PASSWORD
  printf %s "mintoosuite" | gh secret set KEY_ALIAS
  echo "Secrets saved on GitHub."; GH_OK=1
else
  GH_OK=0
  echo "GitHub CLI is not logged in. Either run  gh auth login  and run this script again,"
  echo "or add three secrets by hand on github.com (repo > Settings > Secrets and variables > Actions):"
  echo "  KEYSTORE_B64      = the text inside $KDIR/keystore.b64"
  echo "  KEYSTORE_PASSWORD = the password you just typed"
  echo "  KEY_ALIAS         = mintoosuite"
fi
unset P1 P2

echo "== 5/5 Publishing the project and building"
printf 'keystore.b64\n*.jks\n' >> .gitignore
git add android .github .gitignore
git commit -m "Add signed Android build" >/dev/null 2>&1 || true
git push || { echo "Push failed. If it mentions 'workflow' scope, create a new GitHub token that includes the workflow permission, log in again, and rerun."; exit 1; }
if [ "$GH_OK" = 1 ]; then
  gh workflow run android.yml && sleep 8
  RID=$(gh run list --workflow android.yml --limit 1 --json databaseId -q '.[0].databaseId')
  echo "Building (about 5 to 8 minutes)..."
  if gh run watch "$RID" --exit-status; then
    rm -rf "$HOME/mintoo_build"; gh run download "$RID" -D "$HOME/mintoo_build"
    echo "DONE. Files:"; find "$HOME/mintoo_build" -type f
    [ -d "$HOME/storage/downloads" ] && cp -r "$HOME/mintoo_build" "$HOME/storage/downloads/MintooSuite_signed" && echo "Copied to your phone Downloads/MintooSuite_signed"
  else
    echo "The build failed. Open GitHub > Actions > the failed run, copy the red error lines and send them to me."
  fi
else
  echo "Now open GitHub > your repo > Actions > Build signed Android app > Run workflow, then download MintooSuite-signed."
fi
